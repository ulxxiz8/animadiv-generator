import { DEFAULT_ANIMATION_CONFIG } from '../utils/elementSystem';

const CATEGORY = {
  button: 'Buttons',
  text: 'Typography',
  input: 'Inputs',
  textarea: 'Inputs',
  checkbox: 'Inputs',
  radio: 'Inputs',
  image: 'Images',
  link: 'Links',
  block: 'Blocks',
};

const keyPart = (value) =>
  String(value || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const animation = (presetId = 'none', overrides = {}) => ({
  ...DEFAULT_ANIMATION_CONFIG,
  presetId,
  ...overrides,
});

const motion = ({ load, hover, click, static: staticLoop } = {}) => ({
  load: animation(load?.presetId || 'none', load),
  static: animation(staticLoop?.presetId || 'none', staticLoop),
  hover: animation(hover?.presetId || 'none', hover),
  click: animation(click?.presetId || 'none', click),
});

const shadow = (overrides = {}) => ({
  shadowEnabled: false,
  shadowColor: '#111827',
  shadowOpacity: 0.14,
  shadowOffsetX: 0,
  shadowOffsetY: 10,
  shadowBlur: 24,
  shadowSpread: 0,
  ...overrides,
});

const meta = ({ id, name, type, collection, motionStyle, intensity = 'Medium', tags = [], previewBackground = '#F8FAFC', previewAccent = '#D6F854' }) => {
  const category = CATEGORY[type] || 'Blocks';

  return {
    id,
    name,
    nameKey: `library.items.${id}.name`,
    category,
    categoryKey: `library.categories.${category}`,
    collection,
    collectionKey: `library.collections.${keyPart(collection)}`,
    motionStyle,
    motionStyleKey: `library.motionStyles.${keyPart(motionStyle)}`,
    intensity,
    intensityKey: `library.intensity.${keyPart(intensity)}`,
    tags,
    tagKeys: tags.map((tag) => `library.tags.${keyPart(tag)}`),
    preview: {
      background: previewBackground,
      accent: previewAccent,
    },
  };
};

