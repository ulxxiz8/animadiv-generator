const animation = (overrides = {}) => ({
  ...DEFAULT_ANIMATION_CONFIG,
  ...overrides,
});

const animations = ({ load = {}, hover = {}, click = {} } = {}) => ({
  load: animation(load),
  hover: animation({ presetId: 'none', ...hover }),
  click: animation({ presetId: 'none', ...click }),
});

