import { DEFAULT_ANIMATION_CONFIG } from '../utils/elementSystem';

const animation = (overrides = {}) => ({
  ...DEFAULT_ANIMATION_CONFIG,
  ...overrides,
});

const animations = ({ load = {}, hover = {} } = {}) => ({
  load: animation(load),
  hover: animation(hover),
  click: animation({ presetId: 'none' }),
});

const shadow = (overrides = {}) => ({
  shadowEnabled: true,
  shadowColor: '#111827',
  shadowBlur: 24,
  shadowOffsetY: 10,
  shadowOpacity: 0.12,
  ...overrides,
});

const preview = (background, accent = '#D6F854') => ({
  background,
  accent,
});

const previewMotion = (type, duration = 640, intensity = 50) => ({
  trigger: 'hover',
  type,
  duration,
  intensity,
});

const meta = ({
  id,
  name,
  category,
  collection,
  motionStyle,
  intensity,
  tags = [],
  displayType,
  previewMotion: itemPreviewMotion,
}) => ({
  id,
  name,
  category,
  collection,
  motionStyle,
  intensity,
  tags,
  displayType,
  previewMotion: itemPreviewMotion,
});

